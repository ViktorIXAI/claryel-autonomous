#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Publish the bank-identity probe arms (v6.2 / v6.3 / v6.4 on B-ex6-04) into
benchmarks/hard/v6-results/bank-probe-634/, sanitized with the same rules as
scripts/publish_pair_arms.py (LAN IPs, hostnames, /home|/Users paths, bearer
tokens, key-file references). Ledger rows score, results rows carry bytes: both
are copied per arm plus the run record, log and epoch markers, so an outside
reader can re-derive every number in BANK-PROBE-634.md.
"""
import json
import os
import re
import shutil
import sys

WS = {
    "62": os.path.expanduser("~/parb-v62-probe"),
    "63": os.path.expanduser("~/parb-v63-probe"),
    "64": os.path.expanduser("~/parb-v64-probe"),
}
RIDS = {t: ["p%sr%d" % (t, r) for r in (22, 23, 24)] for t in WS}
DST = "benchmarks/hard/v6-results/bank-probe-634"

# Same masking family as scripts/publish_pair_arms.py RULES.
RULES = [
    (re.compile(r"192\.168\.\d{1,3}\.\d{1,3}"), "<LAN_IP>"),
    (re.compile(r"\bclaryel01\b"), "<HOST>"),
    (re.compile(r"(?:home|Users|mnt|srv|opt)/[^\s\"]*"), "<LOCAL_PATH>"),
    (re.compile(r"(?i)bearer\s+[A-Za-z0-9._\-]{8,}"), "Bearer [REDACTED]"),
    (re.compile(r"(?i)(api[_-]?key|token|secret)\s*[:=]\s*\"?[A-Za-z0-9._\-]{8,}"), r"\1: [REDACTED]"),
    (re.compile(r"p2005-profile\.json"), "<KEYFILE>"),
    (re.compile(r"\bclaryel@|\bviktor@"), "<user>@"),
]


def sanitize(text):
    for rx, rep in RULES:
        text = rx.sub(rep, text)
    return text


def main():
    os.makedirs(DST, exist_ok=True)
    written = 0
    for tag, rids in RIDS.items():
        for rid in rids:
            src = WS[tag]
            for name in ("results-%s.jsonl" % rid, "ledger-%s.jsonl" % rid,
                         "run-record-%s.json" % rid, "%s.log" % rid,
                         "%s-start.epoch" % rid, "%s-end.epoch" % rid):
                p = os.path.join(src, name)
                if not os.path.exists(p):
                    print("MISSING %s/%s" % (src, name))
                    continue
                if name.endswith((".jsonl", ".json", ".log", ".epoch")):
                    raw = open(p, encoding="utf-8", errors="replace").read()
                    open(os.path.join(DST, name), "w", encoding="utf-8").write(sanitize(raw))
                    written += 1
    for src, out in ((os.path.expanduser("~/parb-v63-probe/run_bank63_probe.sh"), "run_bank63_probe.sh"),
                     (os.path.expanduser("~/parb-v64-probe/run_bank64_probe.sh"), "run_bank64_probe.sh")):
        if os.path.exists(src):
            open(os.path.join(DST, out), "w", encoding="utf-8").write(
                sanitize(open(src, encoding="utf-8").read()))
            written += 1
    # probe summary table, regenerated from the copied rows (never retyped)
    rows = []
    for tag in ("62", "63", "64"):
        for rid in RIDS[tag]:
            led = [json.loads(l) for l in open(os.path.join(DST, "ledger-%s.jsonl" % rid), encoding="utf-8") if l.strip()]
            res = {(x["task"], x["rep"]): x for x in
                   (json.loads(l) for l in open(os.path.join(DST, "results-%s.jsonl" % rid), encoding="utf-8") if l.strip())}
            for l in led:
                ans = res.get((l["task"], l["rep"]), {}).get("answer", "") or ""
                if not ans.strip():
                    sys.exit("FATAL: blank joined answer for %s" % rid)
                rows.append((rid, l["task"], l["rep"], l["content"], bool(l["format_ok"]),
                             l["content"] == 1.0 and bool(l["format_ok"]), l.get("codes"),
                             l.get("ptok"), l.get("ctok"), l.get("seconds"),
                             l.get("model_calls"), ans))
    lines = ["# bank-identity probe rows (regenerated by scripts/publish_bank_probe.py)",
             "",
             "| arm | task | rep | content | format_ok | strict | codes | ptok | ctok | s | calls | answer |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ans = r[11].replace("|", "\\|").replace("\n", " ")
        lines.append("| %s | %s | %d | %s | %s | %s | %s | %s | %s | %s | %s | `%s` |" % (
            r[0], r[1], r[2], r[3], r[4], "PASS" if r[5] else "fail",
            ",".join(r[6]) if r[6] else "-", r[7], r[8], r[9], r[10], ans[:120]))
    strict = {t: sum(1 for r in rows if r[0].startswith("p" + t) and r[5]) for t in ("62", "63", "64")}
    lines += ["", "strict by bank tag (of 3, identical sp1 seeds): "
              + ", ".join("v6.%s=%d/3" % (t[-1], strict[t]) for t in ("62", "63", "64"))]
    open(os.path.join(DST, "PROBE-ROWS.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote %d sanitized files + PROBE-ROWS.md into %s" % (written, DST))
    print("strict:", strict)


main()
