#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Answer-by-answer audit of the contract-sensitive categories (F, H, K) across all four arms.

The independent review asked for exactly this: every F/H/K cell, per arm, traced from the published
answer bytes to the frozen scorer verdict, with the scorer's own reason string as the failure note.
Classification is rule-based, not hand-waved, and is labelled as such:

  pass                 strict-eligible (content 1.0 and format_ok)
  content              content < 1.0  (the answer is wrong or incomplete, format was fine)
  format_only          content == 1.0 but format_ok false (right content, wrong wrapping)
  bank_defect          the cell is listed in bank-defect-b04.md as not answerable as written
  e_sandbox            category E style execution required (not applicable in F/H/K, kept defensive)

Usage: python3 scripts/fhk_answer_audit.py > benchmarks/hard/v6-results/AUDIT-FHK-60.md
"""
import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BANK = os.path.join(ROOT, "benchmarks", "hard", "bank-hard-v6.json")
FOUR = os.path.join(ROOT, "benchmarks", "hard", "v6-results", "four-arm-v61")
FULL229 = os.path.join(ROOT, "benchmarks", "hard", "v6-results", "full-229")
CATS = ("F", "H", "K")
DEFECTS = {"B-ex6-04", "H-ex6-01", "K-ex6-03"}


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None, "missing harness module: " + path
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


CK = _load("ck", os.path.join(ROOT, "harness", "parb_check_v6.py"))


def strict(c, f):
    return c == 1.0 and bool(f)


def main() -> int:
    bank = {t["id"]: t for t in json.load(open(BANK, encoding="utf-8"))}
    ids = sorted(k for k in bank if bank[k]["cat"] in CATS and bank[k].get("mode") != "loop")
    arms = {}
    for arm in ("basalt", "codex", "grok"):
        rows = {}
        for line in open(os.path.join(FOUR, "answers-%s-v61.jsonl" % arm), encoding="utf-8"):
            r = json.loads(line)
            rows[r["task"]] = r.get("answer") or ""
        arms[arm] = rows
    contour = {}
    for line in open(os.path.join(FULL229, "results-c229full.jsonl"), encoding="utf-8"):
        r = json.loads(line)
        if str(r.get("rep")) == "0":
            contour[r["task"]] = r
    ecache = json.load(open(os.path.join(FOUR, "E-EXEC.json"), encoding="utf-8"))
    print("# Answer-by-answer audit: F/H/K (%d tasks x 4 arms)" % len(ids))
    print()
    print("Generated by `scripts/fhk_answer_audit.py` from published answer bytes; the frozen scorer "
          "(`harness/parb_check_v6.py`) produced every verdict below, and the note is the scorer's own "
          "reason string, truncated to 90 characters. Rule-based classification, no hand editing.")
    print()
    print("| task | cat | verdict (basalt / ChatGPT / Grok / contour) | content 1.0? (same order) | note |")
    print("|---|---|---|---|---|")
    tally = {a: {"pass": 0, "content": 0, "format_only": 0} for a in ("basalt", "codex", "grok", "contour")}
    for tid in ids:
        task = bank[tid]
        verdicts = []
        contents = []
        notes = []
        for arm in ("basalt", "codex", "grok"):
            ans = arms[arm].get(tid, "")
            c, f, detail = CK.check(task, ans)
            ok = strict(c, f)
            verdicts.append("PASS" if ok else "fail")
            contents.append("%.2f/%s" % (c, "T" if f else "F"))
            cls = "pass" if ok else ("format_only" if c == 1.0 else "content")
            if tid in DEFECTS:
                cls = "bank_defect?" + cls
            tally[arm][cls.replace("bank_defect?", "")] += 1
            if detail:
                notes.append("%s: %s" % (arm, str(detail)[:90]))
        r = contour.get(tid, {})
        c, f = r.get("content") or 0, bool(r.get("format_ok"))
        verdicts.append("PASS" if strict(c, f) else "fail")
        contents.append("%.2f/%s" % (c, "T" if f else "F"))
        tally["contour"]["pass" if strict(c, f) else ("format_only" if c == 1.0 else "content")] += 1
        ev = r.get("contour_events") or []
        if ev:
            notes.append("contour events: " + ",".join(ev)[:90])
        note = "; ".join(notes[:2]) or "—"
        print("| %s | %s | %s | %s | %s |" % (
            tid, task["cat"], " / ".join(verdicts), " / ".join(contents), note.replace("|", "/")))
    print()
    print("Tally over these %d cells:" % len(ids))
    for arm in ("basalt", "codex", "grok", "contour"):
        t = tally[arm]
        print("  %-8s pass %d  content-fail %d  format-only-fail %d" % (
            arm, t["pass"], t["content"], t["format_only"]))
    print()
    print("Known bank defects among these cells: " + ", ".join(sorted(DEFECTS & set(ids))) +
          " — see `bank-defect-b04.md`. A `bank_defect?` class does not remove the cell from any "
          "scoreboard; it marks that the reference may be unreachable from the prompt.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
